"""Writes docs/RESULTS.md from the metrics produced by train.py, so the numbers in the report
always come from a real training run. Usage: python make_report.py [path/to/metrics.json]"""
import json, sys, datetime
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "server" / "data" / "metrics.json"
data = json.loads(src.read_text())
models, meta = data["models"], data["meta"]
p = lambda v: f"{v * 100:.1f}"

lines = [
    "# Results", "",
    f"_Generated by `ml/make_report.py` from `{src.name}` on {datetime.date.today().isoformat()}. Do not edit by hand; re-run `python train.py` and `python make_report.py` instead._", "",
    f"Training patients: **{meta['n_train']}**. Held-out test patients: **{meta['n_test']}**. Split: 80:20, stratified, `random_state=42`. "
    "Cross-validation: 5-fold stratified on the training patients only.", "",
    "## Held-out test set and cross-validation", "",
    "| Model | Test accuracy | Precision | Recall | F1 | AUC | CV accuracy (mean ± sd) |",
    "|---|---:|---:|---:|---:|---:|---:|",
]
for m in models.values():
    lines.append(f"| {m['name']} | {p(m['accuracy'])} | {p(m['precision'])} | {p(m['recall'])} | {p(m['f1'])} | {m['auc']:.3f} | {p(m['cv_mean'])} ± {p(m['cv_std'])} |")
best = max(models.values(), key=lambda m: m["cv_mean"])
lines += ["", f"Best cross-validated accuracy: **{best['name']}** at {p(best['cv_mean'])}%. "
          "With so few test patients one misclassification moves test accuracy by more than a point, so prefer the cross-validated column when comparing models.", "",
          "## Confusion matrices (test set)", "",
          "| Model | True negative | False positive | False negative | True positive |", "|---|---:|---:|---:|---:|"]
for m in models.values():
    c = m["confusion"]; lines.append(f"| {m['name']} | {c['tn']} | {c['fp']} | {c['fn']} | {c['tp']} |")
lines += ["", "## Feature importance (Random Forest)", "", "| Rank | Feature | Importance |", "|---:|---|---:|"]
for i, f in enumerate(meta["importance"], 1):
    lines.append(f"| {i} | `{f['feature']}` | {f['value']:.3f} |")
out = root / "docs" / "RESULTS.md"; out.parent.mkdir(exist_ok=True); out.write_text("\n".join(lines) + "\n")
print("wrote", out)
